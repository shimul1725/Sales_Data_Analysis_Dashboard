import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import plotly.express as px

# Ensure output directories exist
visual_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'reports', 'visualizations'))
os.makedirs(visual_dir, exist_ok=True)

# Load cleaned dataset
data_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'data', 'processed', 'Superstore_cleaned.csv'))
df = pd.read_csv(data_path)

# Basic preprocessing for dates
if 'order_date' in df.columns:
    df['order_date'] = pd.to_datetime(df['order_date'], errors='coerce')
    df['order_month'] = df['order_date'].dt.to_period('M').astype(str)

# 1. Correlation analysis
numeric_cols = ['sales', 'profit', 'quantity', 'discount']
corr = df[numeric_cols].corr()
plt.figure(figsize=(8,6))
sns.heatmap(corr, annot=True, cmap='coolwarm', fmt='.2f')
plt.title('Correlation Matrix')
corr_path = os.path.join(visual_dir, 'correlation_heatmap.png')
plt.tight_layout()
plt.savefig(corr_path)
plt.close()

# 2. Monthly sales trend
monthly_sales = df.groupby('order_month')['sales'].sum().reset_index()
plt.figure(figsize=(10,6))
sns.lineplot(data=monthly_sales, x='order_month', y='sales', marker='o')
plt.xticks(rotation=45)
plt.title('Monthly Sales Trend')
plt.xlabel('Month')
plt.ylabel('Total Sales')
monthly_path = os.path.join(visual_dir, 'monthly_sales_trend.png')
plt.tight_layout()
plt.savefig(monthly_path)
plt.close()

# 3. Profit distribution
plt.figure(figsize=(8,6))
sns.histplot(df['profit'], kde=True, bins=50)
plt.title('Profit Distribution')
plt.xlabel('Profit')
profit_path = os.path.join(visual_dir, 'profit_distribution.png')
plt.tight_layout()
plt.savefig(profit_path)
plt.close()

# 4. Sales by Category (bar chart)
category_sales = df.groupby('category')['sales'].sum().reset_index().sort_values('sales', ascending=False)
plt.figure(figsize=(8,6))
sns.barplot(data=category_sales, x='sales', y='category', palette='viridis')
plt.title('Total Sales by Category')
plt.xlabel('Sales')
plt.ylabel('Category')
category_path = os.path.join(visual_dir, 'sales_by_category.png')
plt.tight_layout()
plt.savefig(category_path)
plt.close()

# 5. Top 10 profitable products (interactive Plotly bar)
product_profit = df.groupby('product_name')['profit'].sum().reset_index().sort_values('profit', ascending=False).head(10)
fig = px.bar(product_profit, x='profit', y='product_name', orientation='h', title='Top 10 Profitable Products')
fig.update_layout(yaxis={'categoryorder':'total ascending'})
product_path = os.path.join(visual_dir, 'top10_profitable_products.html')
fig.write_html(product_path)

# 6. Save summary statistics to a markdown report
report_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'reports', 'advanced_eda_report.md'))
with open(report_path, 'w', encoding='utf-8') as f:
    f.write('# Advanced Exploratory Data Analysis Report\n\n')
    f.write('## Dataset Overview\n')
    f.write(f'- Rows: {df.shape[0]}\n')
    f.write(f'- Columns: {df.shape[1]}\n')
    f.write('## Correlation Matrix\n')
    f.write(f'![Correlation Heatmap]({os.path.relpath(corr_path, os.path.dirname(report_path)).replace("\\", "/")})\n\n')
    f.write('## Monthly Sales Trend\n')
    f.write(f'![Monthly Sales Trend]({os.path.relpath(monthly_path, os.path.dirname(report_path)).replace("\\", "/")})\n\n')
    f.write('## Profit Distribution\n')
    f.write(f'![Profit Distribution]({os.path.relpath(profit_path, os.path.dirname(report_path)).replace("\\", "/")})\n\n')
    f.write('## Sales by Category\n')
    f.write(f'![Sales by Category]({os.path.relpath(category_path, os.path.dirname(report_path)).replace("\\", "/")})\n\n')
    f.write('## Top 10 Profitable Products (interactive)\n')
    f.write(f'[Interactive Plot]({os.path.relpath(product_path, os.path.dirname(report_path)).replace("\\", "/")})\n\n')
    f.write('---\n')
    f.write('Generated by advanced_eda.py script.')

print('Advanced EDA completed. Reports and visualizations saved.')
